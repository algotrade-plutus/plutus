@dataclass(frozen=True)
class FillQuestion:
    """One ``(order, interval)`` question, with everything ``evaluate`` needs.

    A named bundle rather than a tuple because ``already_filled`` and
    ``instrument`` are exactly the two arguments a caller forgets, and
    forgetting either changes the answer: no ``already_filled`` evades the
    participation cap, and no ``instrument`` falls back to the venue-and-date
    lot, which is date-correct but cannot express a *per-instrument* one (see
    :meth:`BaseFillPolicy._lot`).
    """

    order: OrderRecord
    interval: MarketInterval
    rules: Exchange
    already_filled: int = 0
    instrument: Optional[InstrumentSpec] = None
    label: Optional[str] = None
    """The caller's own tag for this row. Defaults to
    ``'<order_id>@<interval start>'``."""

    @property
    def name(self) -> str:
        return self.label or f'{self.order.order_id}@{self.interval.start}'


@dataclass(frozen=True)
class DivergenceRow:
    """What every compared policy said about one question."""

    name: str
    ticker: str
    start: datetime
    decisions: Mapping[str, FillDecision]
    """Policy signature -> its decision. Keyed by signature rather than by
    ``kind`` so that two ``hard`` policies at different caps, or a sweep over
    ``p_touch``, are distinguishable columns."""

    @property
    def outcomes(self) -> Mapping[str, FillOutcome]:
        return {sig: d.outcome for sig, d in self.decisions.items()}

    @property
    def quantities(self) -> Mapping[str, int]:
        return {sig: d.quantity for sig, d in self.decisions.items()}

    @property
    def outcomes_agree(self) -> bool:
        """Whether every policy reached the same ``FillOutcome``."""
        return len(set(self.outcomes.values())) <= 1

    @property
    def agreed(self) -> bool:
        """Whether the policies are indistinguishable on this question.

        Stricter than :attr:`outcomes_agree`, and deliberately: two policies
        that both say ``FILL`` for 1,000 and for 100 shares have diverged, and
        a comparison that scored that as agreement would hide the entire effect
        of the participation cap.
        """
        answers = {(d.outcome, d.quantity, d.price)
                   for d in self.decisions.values()}
        return len(answers) <= 1


@dataclass(frozen=True)
class DivergenceReport:
    """Where a set of policies agreed and where they did not.

    **A standard reporting mode, not a contribution.** Forex Strategy Builder
    shipped a Method Comparator in 2011 that ran a strategy under each member
    of an ``InterpolationMethod`` family and plotted the divergence, alongside
    a ``BacktestEval.Ambiguous`` status and a reported ``AmbiguousBars``
    statistic; NautilusTrader's ``FillModel`` carries the same hard/soft/
    probabilistic knob; Claeys (2026) reports a best-case/worst-case spread
    over 2,064,460 E-mini bars. This class is that tool applied to Vietnamese
    exchange rules, where the ambiguity is generated by the ATO/ATC cross, the
    band lock and the tick and lot grids rather than by intrabar path
    geometry -- and where a policy may answer ``INDETERMINATE``, which is
    counted here as a first-class column rather than folded into "no fill".
    See ``docs/reference/literature-review.md`` sections 2.4 and 4.3.

    **It reports fills, not performance.** No return, no P&L, no Sharpe: this
    package is the exchange, not a backtester (design section 3), and the
    caller who owns the strategy owns those. What is here is what the exchange
    can honestly say -- outcome per policy, quantity per policy, where they
    disagree, and how much of the flow each policy could not decide.
    """

    signatures: Tuple[str, ...]
    rows: Tuple[DivergenceRow, ...]
    assumptions: Mapping[str, Tuple[str, ...]]
    """Signature -> that policy's ``assumptions``. Carried so a printed
    comparison states what each column assumed; design section 16 requires the
    fill assumption to travel with the result, and a table of three columns is
    three assumptions, not one."""

    @property
    def questions(self) -> int:
        return len(self.rows)

    @property
    def divergent(self) -> Tuple[DivergenceRow, ...]:
        """Only the rows on which the policies did not give one answer."""
        return tuple(row for row in self.rows if not row.agreed)

    @property
    def agreement_rate(self) -> Optional[Decimal]:
        """Share of questions every policy answered identically.

        ``None`` for an empty flow -- 0/0 is not 100% agreement, and reporting
        it as such is how an empty run gets published as a clean one.
        """
        if not self.rows:
            return None
        agreed = sum(1 for row in self.rows if row.agreed)
        return Decimal(agreed) / Decimal(len(self.rows))

    def outcomes(self, signature: str) -> Mapping[FillOutcome, int]:
        """How one policy answered, counted by outcome."""
        counts: Dict[FillOutcome, int] = {o: 0 for o in FillOutcome}
        for row in self.rows:
            counts[row.decisions[signature].outcome] += 1
        return counts

    def indeterminate_rate(self, signature: str) -> Optional[Decimal]:
        """One policy's bound on its own ignorance over this flow.

        The same measurement ``IndeterminateReport`` makes for a whole session,
        computed here per policy so that the three arms' ignorance rates can be
        read off one table. ``None`` on an empty flow.
        """
        if not self.rows:
            return None
        return (Decimal(self.outcomes(signature)[FillOutcome.INDETERMINATE])
                / Decimal(len(self.rows)))

    def filled_quantity(self, signature: str) -> int:
        """Total quantity one policy would have executed over this flow.

        Quantity, not value and not P&L: the spread in *shares filled* is a
        statement the exchange can make. What that spread was worth is the
        caller's arithmetic, on the caller's side of the boundary.
        """
        return sum(row.decisions[signature].quantity
                   for row in self.rows
                   if row.decisions[signature].outcome is FillOutcome.FILL)

    def table(self) -> str:
        """The report as fixed-width text, policies as columns.

        Deliberately plain text and deliberately on this object: a comparison
        printed without the signatures that produced it is unattributable, so
        the header is the signature list, not ``soft``/``hard``/``prob``.
        """
        head = ['question']
        head.extend(self.signatures)
        widths = [max(len(head[0]),
                      *(len(row.name) for row in self.rows))] if self.rows \
            else [len(head[0])]
        for i, sig in enumerate(self.signatures, start=1):
            cells = [_cell(row.decisions[sig]) for row in self.rows]
            widths.append(max([len(head[i])] + [len(c) for c in cells]))

        lines = [
            '  '.join(h.ljust(w) for h, w in zip(head, widths)),
            '  '.join('-' * w for w in widths),
        ]
        for row in self.rows:
            cells = [row.name.ljust(widths[0])]
            for i, sig in enumerate(self.signatures, start=1):
                cells.append(_cell(row.decisions[sig]).ljust(widths[i]))
            marker = '' if row.agreed else '   <- diverges'
            lines.append('  '.join(cells).rstrip() + marker)

        rate = self.agreement_rate
        lines.append('')
        lines.append(f'{self.questions} questions, '
                     f'{len(self.divergent)} divergent, '
                     f'agreement {"n/a" if rate is None else rate}')
        for sig in self.signatures:
            ind = self.indeterminate_rate(sig)
            lines.append(f'  {sig}: filled {self.filled_quantity(sig)}, '
                         f'indeterminate '
                         f'{"n/a" if ind is None else ind}')
        return '\n'.join(lines)


def compare_policies(
    policies: Sequence[FillPolicy],
    flow: Iterable[FillQuestion],
) -> DivergenceReport:
    """Run one order flow under several policies and report the divergence.

    The standard multi-policy comparison (see :class:`DivergenceReport` for the
    prior art it follows), with two things fixed for this package:

    * the flow is evaluated **question by question rather than policy by
      policy**, so a policy carrying internal state could not accumulate a
      different history than its neighbours and quietly make the comparison
      about the ordering. :class:`ProbabilisticFillPolicy` is stateless by
      construction and does not need this, but a third-party
      :class:`FillPolicy` may not be;
    * every column is keyed by its **signature**, so a comparison of two
      ``hard`` policies at different caps, or a sweep over ``p_touch``, is a
      legible table rather than three columns all called ``hard``.

    Exceptions from a policy are **not** caught. A ticker mismatch or a
    ``Side.CROSS`` is an integration bug, and swallowing one into a table cell
    would publish a bug as a divergence between assumptions.

    Args:
        policies: two or more. One policy has nothing to diverge from, and a
            report that always says "100% agreement" is worse than an error.
        flow: the questions, in any order. Nothing here depends on their
            order, which is a property worth having and worth testing.

    Raises:
        ValueError: on fewer than two policies, or on two policies sharing a
            signature -- the second would silently overwrite the first in every
            row, and the table could not attribute either.
    """
    signatures: List[str] = []
    for policy in policies:
        signature = getattr(policy, 'signature', getattr(policy, 'kind', ''))
        if not signature:
            raise ValueError(
                f'{policy!r} has neither a signature nor a kind, so its column '
                f'could not be labelled and its decisions could not be '
                f'attributed'
            )
        if signature in signatures:
            raise ValueError(
                f'two policies share the signature {signature!r}; a comparison '
                f'keyed by signature could not tell their columns apart. Give '
                f'them different parameters, or compare them in separate runs'
            )
        signatures.append(signature)
    if len(signatures) < 2:
        raise ValueError(
            f'a comparison needs at least two policies, got {len(signatures)}')

    rows: List[DivergenceRow] = []
    for question in flow:
        decisions: Dict[str, FillDecision] = {}
        for policy, signature in zip(policies, signatures):
            decisions[signature] = policy.evaluate(
                question.order, question.interval, question.rules,
                already_filled=question.already_filled,
                instrument=question.instrument,
            )
        rows.append(DivergenceRow(
            name=question.name,
            ticker=question.interval.ticker,
            start=question.interval.start,
            decisions=decisions,
        ))

    return DivergenceReport(
        signatures=tuple(signatures),
        rows=tuple(rows),
        assumptions={
            signature: tuple(getattr(policy, 'assumptions', ()))
            for policy, signature in zip(policies, signatures)
        },
    )


