def floor_to_lot(quantity: int, trading_unit: int) -> int:
    """Floor a quantity to a whole round lot. Convention 2.

    A capped quantity that is not floored leaves the ledger holding an odd lot,
    and an odd lot is not sellable through the ordinary board: ``ROUND_LOT`` in
    ``exchanges/equity.py`` will refuse the sale later, stranding the position
    for a reason the caller cannot see from the fill that created it. Flooring
    at the point of the fill is the only place the problem is cheap.

    ``trading_unit`` of 1 (HNXDS, and odd-lot boards) makes this the identity.

    Raises:
        ValueError: on a negative quantity or a trading unit below 1. Neither
            is a market condition; both are integration bugs, and silently
            returning 0 would hide one.
    """
    if quantity < 0:
        raise ValueError(f'quantity must not be negative, got {quantity}')
    if trading_unit < 1:
        raise ValueError(
            f'trading_unit must be at least 1, got {trading_unit}')
    return (quantity // trading_unit) * trading_unit


def participation_cap(
    interval: MarketInterval,
    max_participation: Decimal,
    already_filled: int,
) -> Optional[int]:
    """Quantity this instrument may still take in this interval, or ``None``.

    Convention 3: the cap is a fraction of the volume **observed in the
    evaluated interval**, aggregated across every one of the caller's own live
    orders in the instrument -- hence ``already_filled`` rather than a
    per-order budget. Per-order, a caller splits one order into ten and evades
    it.

    ``None`` means *the cap cannot be computed*, which is a different answer
    from zero and must not be collapsed into it: zero says "you have used your
    share", ``None`` says "the data does not say what the share is". The caller
    turns ``None`` into an ``INDETERMINATE`` naming ``DataField.VOLUME``.

    **Where that still happens, corrected.** This used to say that both
    shipped adapters leave ``volume`` unsupplied on every corpus here, and
    therefore that a volume-capped policy was undecidable everywhere. That was
    a statement about the adapters, not about the data:
    :class:`~plutus.market.adapters.datahub.DataHubSource` now serves
    ``quote_dailyvolume`` through the ``IntervalSource`` seam, on 62.9% of
    ticker-days in the Parquet root and on every liquid name measured. ``None``
    is still reached, and honestly: on the ticker-days with no volume row, on
    every instrument with no volume to publish (the indices), on
    :class:`~plutus.market.adapters.tick.TickSource`, which serves no
    intervals at all, and on any caller's own source that does not.

    Rounds **down**: a fractional allowance is not a share of a lot.
    """
    if interval.volume is None or interval.lacks(DataField.VOLUME):
        return None
    allowance = (Decimal(interval.volume) * max_participation
                 ).to_integral_value(rounding=ROUND_FLOOR)
    return max(int(allowance) - already_filled, 0)


def auction_fill_price(
    order: OrderRecord,
    interval: MarketInterval,
) -> Optional[Decimal]:
    """The published open (ATO phase) or close (ATC phase). Convention 1.

    A call auction crosses at **one price for everyone**, so there is no
    price-time question to answer and no per-order price: whoever fills, fills
    here. Design section 8 fixes it to the published value, and Tier 3 item 14
    is the separate exercise of computing our own clearing price and grading it
    against this -- evidence, not a feature.

    Which auction is decided by the order type first (ATO opens, ATC closes)
    and by the interval's phase otherwise, so that a limit order carried into
    the cross prices off the auction it actually reached.

    Returns ``None`` in three distinguishable-by-the-caller situations, all of
    which mean "no auction price applies here": this is not an auction interval
    and the order is not auction-only; the order is auction-only and this is
    not its auction; or the auction is right but the published price is absent
    from the data. The caller separates the third by testing ``interval.open`` /
    ``interval.close`` itself, and names ``DataField.OPEN`` / ``CLOSE``.
    """
    phase = _auction_phase(order, interval)
    if phase is None or phase is not interval.session:
        return None
    if phase is SessionPhase.OPENING_AUCTION:
        return interval.open
    return interval.close


# --------------------------------------------------------------------------
# The policy stamp
# --------------------------------------------------------------------------

def stamp_policy(decision: FillDecision, signature: str) -> FillDecision:
    """Record the policy that produced a decision, on the decision.

    Design section 16 assumption 5: "fill determination is policy-dependent,
    and the policy must be reported alongside any result derived from it". A
    stamp applied by the base class rather than by each policy is the
    difference between that being true and it being a convention someone
    remembers.

    Implemented as a ``'<signature>: <why>'`` prefix on ``reason`` because
    ``FillDecision`` has no ``policy`` field yet; see the module docstring for
    the requested change. Idempotent, so a decision that has already been
    stamped by this signature passes through unchanged.

    Raises:
        ValueError: on an empty signature, or one containing the separator --
            either would make :func:`policy_of` unable to read the stamp back,
            and an unreadable stamp is worse than none because it looks present.
    """
    if not signature:
        raise ValueError('a fill policy must have a non-empty signature')
    if POLICY_SEPARATOR in signature:
        raise ValueError(
            f'a policy signature may not contain {POLICY_SEPARATOR!r}, '
            f'got {signature!r}'
        )
    body = decision.reason
    if body is None:
        body = (decision.evidence.value if decision.evidence is not None
                else decision.outcome.value)
    prefix = signature + POLICY_SEPARATOR
    if body.startswith(prefix):
        body = body[len(prefix):]
    # ``replace`` rather than a direct construction: ``FillDecision``'s own
    # docstring reserves positional construction for its three case
    # constructors, and stamping is a copy, not a fourth case.
    return replace(decision, reason=prefix + body)


def policy_of(decision: FillDecision) -> Optional[str]:
    """The signature of the policy that produced ``decision``, if stamped.

    ``None`` for an unstamped decision -- one built by hand in a test, or by a
    third-party policy that implements :class:`FillPolicy` structurally without
    going through :class:`BaseFillPolicy`. ``None`` is the honest answer there;
    inventing a default would attribute someone else's assumption to us.
    """
    reason = decision.reason
    if not reason or POLICY_SEPARATOR not in reason:
        return None
    return reason.split(POLICY_SEPARATOR, 1)[0]


# --------------------------------------------------------------------------
# The size half, shared by every policy that bounds its own claim
# --------------------------------------------------------------------------

class _CappedFillPolicy(BaseFillPolicy):
    """Conventions 2 and 3, in one place, for every policy that applies them.

    ``soft``, ``hard`` and ``probabilistic`` differ on *whether* an order
    filled; they must not differ on *how much* filled once that question is
    answered, or the divergence between the arms stops being attributable to
    the evidence standard. So the participation cap, the round-lot floor, the
    fill-or-kill all-or-nothing rule and the daily-bar auction refusal live
    here rather than once per policy.

    **All three shipped policies derive from it.** ``soft`` did not, and that
    was the defect: it had no cap field, so a configured ``max_participation``
    reached it and vanished. A second, private sizing path in ``soft`` would
    have reintroduced the drift this class exists to prevent, so it inherits
    the same one and merely defaults to ``None``.

    Not public: it is an implementation detail of the shipped policies, and a
    third-party policy satisfies :class:`FillPolicy` structurally without it.
    """

    #: ``None`` means uncapped -- the caller has taken the assumption that
    #: their own size was available. ``soft`` and ``ProbabilisticFillPolicy``
    #: may set it; ``hard`` requires a cap, because "fill only what the data
    #: supports" without a size bound is not the hard standard.
    max_participation: Optional[Decimal] = None

    @staticmethod
    def _validated_participation(
        value: Optional[Decimal],
        *,
        allow_uncapped: bool,
    ) -> Optional[Decimal]:
        """Check a cap, or refuse it. Shared so both policies refuse alike.

        Raises:
            TypeError: if given a ``float``. House rule: every rate is a
                ``Decimal``, because a binary fraction of a share count is a
                rounding bug waiting for a large volume.
            ValueError: outside ``(0, 1]``, or ``None`` where a cap is
                required. Zero would make the policy fill nothing while still
                reporting itself as a fill policy, and above 1 claims more than
                the whole market traded.
        """
        if value is None:
            if allow_uncapped:
                return None
            raise ValueError(
                'max_participation must lie in (0, 1], got None')
        if isinstance(value, float):
            raise TypeError(
                'max_participation must be a Decimal, not a float; rates in '
                'this package are Decimal fractions'
            )
        value = Decimal(value)
        if not Decimal('0') < value <= Decimal('1'):
            raise ValueError(
                f'max_participation must lie in (0, 1], got {value}')
        return value

    def _sized_fill(
        self,
        order: OrderRecord,
        interval: MarketInterval,
        rules: Exchange,
        price: Decimal,
        evidence: FillEvidence,
        *,
        already_filled: int,
        instrument: Optional[InstrumentSpec],
        confidence: Decimal = Decimal('1'),
    ) -> FillDecision:
        """Apply conventions 2 and 3 to an established fill.

        Reached only once the price test has already said yes, so a missing
        volume is reported as ignorance about *this* order rather than about
        every order in the book.

        **A fill-or-kill order is sized all-or-nothing.** The participation
        cap is a statement about liquidity, and for an MOK "1,000 of your
        5,000 would have traded" is not a partial fill -- it is the finding
        that the order *could not be filled in full*, which rulebook 2.3
        (ASEANSC HNX 2.3, high) answers with a kill, not with a fill. So the
        cap binding below the remainder returns ``NO_FILL``, and
        ``exchange.py``'s ``_decide_immediates`` then expires the order with
        ``NOT_FILLABLE_IN_FULL``, which is the only terminal edge locked
        shape 4 gives this time-in-force.

        Returning the partial instead was a reproduced defect: the state
        machine refuses a partially filled MOK outright, so the proposal was
        unsatisfiable, and the ledgers had already paid for it by the time
        the refusal arrived.

        ``NO_FILL`` rather than ``INDETERMINATE`` because the cap *is* the
        answer: the policy has established how much would have traded, and
        that quantity is short. Nothing is unknown here.

        ``confidence`` is 1 for every evidential policy and is the drawn
        probability for :class:`ProbabilisticFillPolicy`; it rides through
        untouched because sizing does not change how sure the policy is that
        *something* filled.

        With ``max_participation`` of ``None`` the whole size question is
        skipped: the caller has declared that they are taking ``soft``'s
        assumption that their own size was available, and there is then no cap
        to compute, no volume to miss, no auction attribution to refuse and no
        round lot to resolve.

        **The round lot is resolved at the instant being filled**, from the
        instrument or from the venue and the interval's date, and a lot that
        cannot be established is a third ``INDETERMINATE`` here -- see
        :meth:`BaseFillPolicy._lot`. The order of the three is deliberate and
        unchanged: the cap is computed first, so a run on a source that does
        not serve volume reports the missing volume, which is the absence a
        data fix could actually close -- and did, for
        :class:`~plutus.market.adapters.datahub.DataHubSource`.
        """
        if self.max_participation is None:
            return FillDecision.fill(order.remaining_quantity, price, evidence,
                                     confidence=confidence)

        if (evidence is FillEvidence.AUCTION_PRICE
                and interval.resolution is Resolution.DAILY):
            # A daily bar's volume is the whole session's, including continuous
            # trading. max_participation of it is not a bound on the auction's
            # own volume, and pretending otherwise would size an auction fill
            # from liquidity that traded hours earlier.
            return FillDecision.indeterminate(
                'a daily bar\'s volume covers the whole session, so the '
                'auction\'s own volume cannot be attributed and the '
                'participation cap cannot be applied to a cross',
                [DataField.VOLUME],
            )

        cap = participation_cap(interval, self.max_participation,
                                already_filled)
        if cap is None:
            return FillDecision.indeterminate(
                'the market traded through the limit, but with no observed '
                'volume the participation cap cannot be computed, so how much '
                'would have filled cannot be established',
                [DataField.VOLUME],
            )
        if cap <= 0:
            # Three distinguishable situations, and the old single sentence --
            # "already exhausted by this caller's own fills" -- was a false
            # claim in two of them: an interval that traded nothing at all, and
            # one whose whole volume is too small for one share of the cap.
            # The numbers are put in the reason rather than a diagnosis, so the
            # sentence is true in all three.
            return FillDecision.no_fill(
                f'a participation cap of {self.max_participation} of the '
                f'{interval.volume} traded in this interval leaves nothing for '
                f'this order after {already_filled} already filled in this '
                f'instrument'
            )

        lot = self._lot(rules, interval, instrument)
        if lot is None:
            # Nothing silently defaults (design section 9.2). A quantity is a
            # claim, and one floored to a lot nobody has established would be a
            # definite fill sized by a guess -- worse than admitting ignorance,
            # because it is not visible in the result. See :meth:`_lot`.
            return FillDecision.indeterminate(
                f'no round lot is known for {rules.spec.code!r} at '
                f'{interval.start.date()}, so a capped quantity cannot be '
                f'floored to a whole lot and how much would have filled '
                f'cannot be established',
                (),
            )
        quantity = floor_to_lot(min(order.remaining_quantity, cap), lot)
        if quantity <= 0:
            return FillDecision.no_fill(
                f'the remaining participation allowance of {cap} is below one '
                f'round lot of {lot}'
            )
        if (order.time_in_force is TimeInForce.FILL_OR_KILL
                and quantity < order.remaining_quantity):
            return FillDecision.no_fill(
                f'a participation cap of {cap} sizes {quantity} of this '
                f'order\'s {order.remaining_quantity}, and a fill-or-kill '
                f'order fills in full at entry or is cancelled entirely '
                f'(rulebook 2.3); it has no partial'
            )
        return FillDecision.fill(quantity, price, evidence,
                                 confidence=confidence)


# --------------------------------------------------------------------------
# SoftFillPolicy -- the baseline arm
# --------------------------------------------------------------------------

class SoftFillPolicy(_CappedFillPolicy):
    """Fill if the price traded at or through the limit. Optionally capped.

    **This is what every backtester does today**, and that is exactly why it
    ships: it is the comparison arm without which "hard fills cost you 1.4
    Sharpe" is a number with nothing to be relative to. It is not the
    recommended policy and its docstring should not be read as endorsing it.

    What it assumes, all of it unstated in the tools that do this by default:

    - that the caller's order was at the front of the queue at its price, on
      every interval, in every instrument -- i.e. that ``TOUCHED_AT_LIMIT`` is
      as good as ``TRADED_THROUGH``;
    - **at ``max_participation=None`` only**, that the caller's size was
      available, whatever it was, with no reference to the volume that
      actually traded;
    - that a market-family order executes at the observed price with no depth.

    Each is recorded on the decision it produced: a soft fill carries
    ``FillEvidence.TOUCHED_AT_LIMIT`` when that is what it rested on, so the
    share of a soft backtest resting on the queue assumption is countable after
    the fact rather than invisible.

    ``INDETERMINATE`` is still reachable, and it matters that it is: when the
    interval carries no traded price at all, even this policy has nothing to
    assert. A policy that could never say "I do not know" would make the
    ``INDETERMINATE`` rate a property of the data alone.

    Why this is a ``_CappedFillPolicy``
    ------------------------------------------------------------------
    It used to be a bare :class:`BaseFillPolicy` with no size question at all,
    and :func:`build_fill_policy` therefore **silently discarded** a
    configured ``max_participation``: ``fill_policy: {kind: soft,
    max_participation: 0.10}`` produced an uncapped run, with no error, no
    warning, and nothing in the provenance record to show that the field the
    caller wrote had been thrown away. That is the exact failure this package
    exists to refuse, and it was invisible to ``indeterminate_report()``
    because an uncapped policy never reaches the ``VOLUME`` branch that would
    have counted it.

    Of the two possible repairs -- teach ``soft`` the cap, or make
    ``build_fill_policy`` refuse ``soft`` together with a cap -- the first is
    the honest one, and it is also the more restrictive direction, which is
    the one a backtest may err in. A refusal would have rejected every
    ``soft`` config ever written, since at the time the config field could not
    distinguish a written 0.10 from an unwritten one at all. It can now
    (``Optional[Decimal] = None``), and a written cap of any value reaches
    this class.

    Sizing lives in :class:`_CappedFillPolicy` rather than being reimplemented
    here for the reason that class exists: the arms of the comparison must
    differ on *whether* an order filled and never on *how much*, or the
    divergence between them stops being attributable to the evidence standard.

    ``max_participation=None`` -- the constructor default, and what
    :func:`compare_policies` gets from a bare ``SoftFillPolicy()`` -- restores
    the original uncapped baseline exactly: :meth:`_CappedFillPolicy._sized_fill`
    short-circuits to the full remaining quantity, so no cap is computed, no
    volume is consulted, no round lot is resolved and no auction attribution is
    refused. The optimistic bound is still available and is still the default;
    it is now *chosen* rather than imposed by an omission.
    """

    kind: ClassVar[str] = 'soft'

    def __init__(self, max_participation: Optional[Decimal] = None) -> None:
        """
        Args:
            max_participation: the fraction of observed interval volume this
                caller may claim across all of its live orders in one
                instrument, or ``None`` for the uncapped optimistic bound.
                ``None`` is the default because an uncapped ``soft`` is the
                comparison arm every other policy is measured against, and a
                silently-capped one would not be that arm. It is carried in
                :attr:`signature` either way, so no result can be reported
                without it.

        Raises:
            TypeError: if given a ``float``. House rule: every rate is a
                ``Decimal``.
            ValueError: outside ``(0, 1]``. Zero would make the policy fill
                nothing while still reporting itself as a fill policy, and
                above 1 claims more than the whole market traded. ``None`` is
                accepted and means uncapped -- unlike ``hard``, for which
                "fill only what the data supports" without a size bound is not
                the hard standard.
        """
        self.max_participation: Optional[Decimal] = (
            self._validated_participation(max_participation,
                                          allow_uncapped=True))

    @property
    def signature(self) -> str:
        """``soft(max_participation=uncapped)``, or the cap when there is one.

        The cap is named **even when there is none**, and the bare token
        ``'soft'`` is deliberately no longer produced by anything. Two runs at
        different caps are two different assumptions and will produce different
        fills, so a signature carrying only the kind cannot reproduce either;
        and a bare ``'soft'`` could not be told apart from a record written
        while the cap was being discarded, which is precisely the period whose
        results must not look like the fixed ones.
        """
        cap = ('uncapped' if self.max_participation is None
               else str(self.max_participation))
        return f'{self.kind}(max_participation={cap})'

    @property
    def assumptions(self) -> Tuple[str, ...]:
        size = (
            'Size: uncapped -- an order fills in full, with no reference to '
            'the volume that actually traded. This is the optimistic bound, '
            'not a forecast.'
            if self.max_participation is None else
            f'Participation cap: at most {self.max_participation} of the '
            f'volume observed in the evaluated interval, aggregated across all '
            f'of the caller\'s live orders in the instrument. A modelling '
            f'convention, not a sourced rule.'
        )
        return super().assumptions + (
            'Soft fills: an order fills whenever the market traded at or '
            'through its limit, with no queue-position test. This is the '
            'optimistic bound on the touch, not a forecast.',
            size,
        )

    def _continuous(self, order, interval, rules, *, already_filled,
                    instrument) -> FillDecision:
        side = order.order.side
        limit = order.order.limit_price

        if limit is None:
            # Market family (MTL/MOK/MAK, and core/order.py's synthetic MKT).
            # The backtester answer: it executes, at whatever printed.
            price = _point_price(interval)
            if price is None:
                return FillDecision.indeterminate(
                    'a market-family order needs an observed traded price and '
                    'this interval carries none',
                    [DataField.CLOSE, DataField.LAST],
                )
            return self._sized_fill(order, interval, rules, price,
                                    FillEvidence.TRADED_THROUGH,
                                    already_filled=already_filled,
                                    instrument=instrument)

        observed, field = _extreme_toward(side, interval)
        if observed is None:
            observed = _point_price(interval)
            if observed is None:
                return FillDecision.indeterminate(
                    'this interval carries no traded price, so not even an '
                    'at-or-through test can be made',
                    [field, DataField.CLOSE, DataField.LAST],
                )

        reach = _reach(side, observed, limit)
        if reach < 0:
            return FillDecision.no_fill(
                f'the market never reached {limit} on the '
                f'{"buy" if side is Side.BUY else "sell"} side '
                f'(best observed {observed})'
            )
        evidence = (FillEvidence.TRADED_THROUGH if reach > 0
                    else FillEvidence.TOUCHED_AT_LIMIT)
        return self._sized_fill(order, interval, rules, limit, evidence,
                                already_filled=already_filled,
                                instrument=instrument)

    def _auction(self, order, interval, rules, *, already_filled,
                 instrument) -> FillDecision:
        clearing, field = _clearing_price(order, interval)
        if clearing is None:
            return FillDecision.indeterminate(
                'no published cross price for this auction, so whether it '
                'crossed at all cannot be established',
                [field] if field is not None else (),
            )

        limit = order.order.limit_price
        if limit is not None and _reach(order.order.side, clearing, limit) < 0:
            return FillDecision.no_fill(
                f'the auction cleared at {clearing}, past a limit of {limit}')
        # A ``limit`` of ``None`` here is an ATO/ATC, or an unmodelled MTL
        # residue. The backtester answer for all of them is the cross price.
        return self._sized_fill(order, interval, rules, clearing,
                                FillEvidence.AUCTION_PRICE,
                                already_filled=already_filled,
                                instrument=instrument)

# --------------------------------------------------------------------------
# HardFillPolicy -- what is defensible going live
# --------------------------------------------------------------------------

class HardFillPolicy(_CappedFillPolicy):
    """Fill only where the data can support the claim that it would have.

    The standard is evidential, and it has exactly one form in each mechanic:

    **Continuous session.** Fill only where the market demonstrably traded
    *through* the limit -- a trade strictly better than our price. That is
    proof: order priority is price first, time second, with no size priority
    and no pro-rata anywhere in Vietnamese rules (rulebook 2.4, QD 352 Dieu 7,
    16, confidence high), so a trade at a price worse than our resting limit
    could not have happened while our order sat unfilled. **Touched at limit
    is INDETERMINATE, not a fill and not a no-fill**: whether we were in front
    of that trade is decided by time priority, and time priority is exactly
    what this corpus cannot recover -- there are no order ids, and 81% of
    best-quote changes carry no trade, so order flow cannot be reconstructed.

    **Call auction.** Fill only where the cross cleared strictly through the
    limit. That is a rule-guaranteed full execution rather than an inference:
    HOSE's clearing algorithm picks the price at which "every buy above and
    every sell below the chosen price fills in full" (rulebook 2.4, QD 352 Dieu
    6.2(a), verbatim, confidence high). At the clearing price exactly, the
    order is rationed, and rulebook 2.4 records allocation at the marginal
    price as **UNVERIFIED for the ATO/ATC cross** -- no Vietnamese document
    states the rule -- so that too is ``INDETERMINATE``.

    **Size.** Capped at ``max_participation`` of the volume observed in the
    interval, then floored to the round lot in force at the instant. Where
    ``interval.volume`` is absent the cap cannot be computed and the decision
    degrades to ``INDETERMINATE`` naming ``DataField.VOLUME``; where the lot
    cannot be resolved it degrades likewise, with no field named because a lot
    is a rulebook fact rather than a bar (:meth:`BaseFillPolicy._lot`). This
    docstring used to say that both shipped adapters leave volume unsupplied
    and that ``hard`` was therefore undecidable wherever it would otherwise
    fill. That was a fact about the adapters and it has been fixed:
    :class:`~plutus.market.adapters.datahub.DataHubSource` serves
    ``quote_dailyvolume``, so on the daily corpus ``hard`` now *fills*.
    ``TickSource`` serves no intervals, so a tick run still degrades.

    The order of those two tests is deliberate and is a modelling choice worth
    naming: **price is tested before size**. An order the market never reached
    is a definite ``NO_FILL`` whatever the volume was, so the missing-volume
    ``INDETERMINATE`` is raised only for orders that would otherwise have
    filled. Testing size first would inflate the reported ignorance rate with
    orders about which the data is perfectly clear.

    What it does *not* claim: that a filled order was actually filled in
    reality. Traded-through establishes that a fill was **possible and
    unavoidable given priority**, on the observed tape, under no market impact.
    It does not model our own order's absence from that tape.
    """

    kind: ClassVar[str] = 'hard'

    def __init__(self, max_participation: Decimal = Decimal('0.10')) -> None:
        """
        Args:
            max_participation: the fraction of observed interval volume this
                caller may claim across all of its live orders in one
                instrument. The 10% default is a **modelling convention, not a
                sourced rule** -- no Vietnamese document caps a participant's
                share of a print -- and it is carried in :attr:`signature` so
                that no result can be reported without it.

        Raises:
            TypeError: if given a ``float``. House rule: every rate is a
                ``Decimal``, because a binary fraction of a share count is a
                rounding bug waiting for a large volume.
            ValueError: outside ``(0, 1]``, or ``None``. Zero would make the
                policy fill nothing while still reporting itself as a fill
                policy, above 1 claims more than the whole market traded, and
                ``hard`` has no uncapped mode -- "fill only what the data
                supports" without a size bound is not the hard standard.
        """
        self.max_participation: Decimal = self._validated_participation(
            max_participation, allow_uncapped=False)

    @property
    def signature(self) -> str:
        """``hard(max_participation=0.10)`` -- the kind *and* the parameter.

        Two runs at different caps are two different assumptions and will
        produce different fills, so the kind alone would not let a reader
        reproduce either one.
        """
        return f'{self.kind}(max_participation={self.max_participation})'

    @property
    def assumptions(self) -> Tuple[str, ...]:
        return super().assumptions + (
            'Hard fills: an order fills only where the market traded strictly '
            'through its limit (continuous) or the cross cleared strictly '
            'through it (auction). At the limit is INDETERMINATE, because '
            'time priority is unrecoverable from this data.',
            f'Participation cap: at most {self.max_participation} of the '
            f'volume observed in the evaluated interval, aggregated across all '
            f'of the caller\'s live orders in the instrument. A modelling '
            f'convention, not a sourced rule.',
        )

    # -- continuous -----------------------------------------------------

    def _continuous(self, order, interval, rules, *, already_filled,
                    instrument) -> FillDecision:
        limit = order.order.limit_price
        if limit is None:
            return self._market_family_undecidable(interval)

        evidence = self._price_test(order, interval)
        if evidence.verdict is _PriceVerdict.SHORT:
            # The extreme of the interval on our side never reached the limit,
            # so nothing traded at or through it. Definite.
            return _no_extreme_reached(evidence, limit)
        if evidence.verdict is _PriceVerdict.AT:
            return _touched(evidence.observed)
        if evidence.verdict is _PriceVerdict.THROUGH:
            return self._sized_fill(order, interval, rules, limit,
                                    FillEvidence.TRADED_THROUGH,
                                    already_filled=already_filled,
                                    instrument=instrument)
        if evidence.verdict is _PriceVerdict.UNPROVEN:
            return _unproven(evidence, limit)
        return _blank(evidence)

    def _market_family_undecidable(self, interval) -> FillDecision:
        """Why ``hard`` never fills MTL/MOK/MAK, and why that is not a gap.

        A market-family order walks the book from the best opposite price and
        its residue converts to a limit one tick beyond the last match
        (rulebook 2.3, QD 352 Dieu 14.2, VNX QD 22/2025 Dieu 17.2(b)). How far
        it walks is a function of **depth**, and ``BookLevel.size`` is ``None``
        on every corpus available here. Assuming it fills at the touch is
        assuming unbounded size at the best price, which is a market-impact
        assumption wearing a different hat -- and section 3 forbids those
        outright. So the honest answer is that the data cannot decide.
        """
        missing = (DataField.BOOK_SIZE if interval.book is not None
                   else DataField.BOOK)
        return FillDecision.indeterminate(
            'a market-family order walks the book, and the depth it would '
            'walk is not observable here; assuming it fills at the touch '
            'would be a market-impact assumption',
            [missing],
        )

    # -- auction --------------------------------------------------------

    def _auction(self, order, interval, rules, *, already_filled,
                 instrument) -> FillDecision:
        clearing, field = _clearing_price(order, interval)
        if clearing is None:
            # An absent published open/close may mean no cross happened or may
            # mean the data does not carry it. Nothing silently defaults
            # (design section 9), so the two are not collapsed into a no-fill.
            return FillDecision.indeterminate(
                'no published cross price for this auction, so whether it '
                'crossed at all cannot be established',
                [field] if field is not None else (),
            )

        limit = order.order.limit_price
        if limit is None:
            tif = TIME_IN_FORCE[order.order.order_type]
            if tif is not TimeInForce.AUCTION_ONLY:
                # An MTL residue rests as a limit one tick beyond the last
                # match (rulebook 2.3); we do not model that conversion, so we
                # do not know the price it would carry into the cross.
                return FillDecision.indeterminate(
                    'a market-family order carries into an auction as its '
                    'residual limit one tick beyond the last match, and that '
                    'conversion is not modelled here',
                    [DataField.BOOK_SIZE],
                )
            # ATO/ATC. Unpriced, added to their side's quantity at every price
            # level in the cross calculation, and matched ahead of all limit
            # orders (rulebook 2.4, QD 352 Dieu 14.3-14.4, unconditional to
            # 2025-05-04 and still ahead of in-band limits after it). An
            # auction-order that reaches a cross is therefore a through-priced
            # order under step (a) and fills in full.
            return self._sized_fill(order, interval, rules, clearing,
                                    FillEvidence.AUCTION_PRICE,
                                    already_filled=already_filled,
                                    instrument=instrument)

        reach = _reach(order.order.side, clearing, limit)
        if reach < 0:
            return FillDecision.no_fill(
                f'the auction cleared at {clearing}, past a limit of {limit}; '
                f'a call auction cannot execute an order priced away from the '
                f'clearing price'
            )
        if reach == 0:
            return FillDecision.indeterminate(
                f'the auction cleared exactly at the limit of {limit}; '
                f'allocation at the marginal price is UNVERIFIED for the '
                f'ATO/ATC cross -- no Vietnamese document states the rule '
                f'(rulebook 2.4)',
                (),
            )
        return self._sized_fill(order, interval, rules, clearing,
                                FillEvidence.AUCTION_PRICE,
                                already_filled=already_filled,
                                instrument=instrument)


# --------------------------------------------------------------------------
# The seeded draw -- reproducibility, and why it is not a random stream
# --------------------------------------------------------------------------

#: Decimal places a draw is reported to. Fixed so the value written into a
#: decision's reason is exactly the value that decided it: a draw a reader
#: cannot recompute is not a record of anything.
DRAW_PRECISION = 18

_DRAW_SPACE = 2 ** 64
_DRAW_SCALE = 10 ** DRAW_PRECISION

#: Domain separation for the hash, so a draw made here can never collide with
#: one some other part of the package makes from the same seed and key.
_DRAW_DOMAIN = b'plutus.fills'


def draw_key(order: OrderRecord, interval: MarketInterval,
             price: Decimal) -> str:
    """The identity of one fill question, as a stable string.

    A draw is a pure function of ``(seed, this key)``, which is what makes the
    whole policy reproducible rather than merely seeded -- see
    :func:`fill_draw`. The key names the *question*, so re-asking it gets the
    same answer:

    * ``order_id`` -- whose order;
    * ticker and the interval's half-open ``[start, end)`` -- which evaluation;
    * the session phase -- an interval evaluated in the auction is a different
      question from the same clock span in continuous session;
    * side and ``price`` -- the price actually being tested, so an amended
      order asking about a new price draws afresh rather than inheriting the
      answer to a question about a price it no longer has.

    Deliberately **not** in the key: ``remaining_quantity``, ``already_filled``
    and the policy's own parameters. A partial fill elsewhere in the run, or a
    sweep over ``p_touch``, must not silently re-roll a decision -- see
    :meth:`ProbabilisticFillPolicy.draw` for the two properties that buys.
    """
    return '|'.join((
        order.order_id,
        interval.ticker,
        interval.start.isoformat(),
        interval.end.isoformat(),
        interval.session.value,
        order.order.side.value,
        str(price),
    ))


def fill_draw(seed: int, key: str) -> Decimal:
    """A uniform draw in ``[0, 1)``, from a seed and a question. Pure.

    **Counter-based, not a stream.** The obvious implementation --
    ``random.Random(seed)`` advanced once per decision -- is seeded but is not
    reproducible in any sense a researcher can use, because the value at step N
    depends on how many draws happened before it. That count is a function of
    the session's iteration order over live orders and intervals, so:

    * adding one unrelated order to a run silently changes the fills of every
      other order in it, which makes two runs incomparable for a reason that
      has nothing to do with what changed;
    * re-evaluating a single order in isolation to explain its fill gives a
      different answer from the one the run gave it, so a fill cannot be
      audited;
    * evaluating the same order twice within a run gives two answers, so the
      policy is not even a function.

    Hashing the question instead removes all three. This is the standard
    counter-based construction (Salmon et al., *Parallel Random Numbers: As
    Easy as 1, 2, 3*, SC'11 -- Random123/Philox), applied here for its
    order-independence rather than for parallel speed; NautilusTrader's
    ``FillModel`` takes a ``random_seed`` for the same purpose from the stream
    side. Nothing about it is novel and it should not be presented as such.

    BLAKE2b is used rather than :func:`hash`, whose string hashing is salted
    per process by ``PYTHONHASHSEED`` and would make a run irreproducible
    across two invocations of the same script. The digest is 64 bits, floored
    onto a grid of ``10 ** DRAW_PRECISION`` points, and computed in a local
    Decimal context so that a caller's ambient ``decimal.getcontext()`` cannot
    change the answer.

    The half-open range is load-bearing at both ends: ``p = 0`` never fills
    (no draw is below zero) and ``p = 1`` always fills (no draw reaches one),
    matching NautilusTrader's documented ``prob_fill_on_limit`` endpoints.
    """
    digest = hashlib.blake2b(
        f'{seed}|{key}'.encode('utf-8'),
        digest_size=8,
        person=_DRAW_DOMAIN,
    ).digest()
    scaled = int.from_bytes(digest, 'big') * _DRAW_SCALE // _DRAW_SPACE
    with localcontext() as ctx:
        ctx.prec = DRAW_PRECISION + 8
        return Decimal(scaled).scaleb(-DRAW_PRECISION)


# --------------------------------------------------------------------------
# ProbabilisticFillPolicy -- the middle arm
# --------------------------------------------------------------------------

class ProbabilisticFillPolicy(_CappedFillPolicy):
    """Fill at the touch with probability ``p_touch``; seeded and recorded.

    The third arm of the same axis the other two occupy. ``soft`` fills every
    touch, ``hard`` calls every touch ``INDETERMINATE``, and this policy draws.
    It is deliberately the *same axis*: everywhere the data is decisive, this
    policy returns exactly what ``hard`` returns, because it consumes the same
    :meth:`BaseFillPolicy._price_test` and the same sizing. The only decision
    it makes differently is the one at the touch.

    **Not novel, and must not be written up as if it were.** NautilusTrader
    ships ``FillModel(prob_fill_on_limit=..., random_seed=...)`` documented as
    *"0.0: Never fill on touch. 0.5: Fill on half of eligible touches on
    average. 1.0: Always fill on touch"*, which is this policy's ``p_touch``
    under another name; the parameter is named for the same semantics on
    purpose, so a reader of both can see they are the same knob. Forex Strategy
    Builder shipped a ``Random`` member of its ``InterpolationMethod`` family
    in 2011. See ``docs/reference/literature-review.md`` sections 2.4 and 4.3.

    What ``p_touch`` is, and what it is not
    ------------------------------------------------------------------
    It is **a number the caller supplies**, carried through to the result, and
    it is not derived from anything. Design section 8 sketched this policy as
    *"fill probability from queue estimate and observed volume"*; that policy
    cannot be written on any corpus available here, because a queue estimate
    needs ``BookLevel.size`` and ``quote_asksize``/``quote_bidsize`` are 0-row
    in both roots. Rather than compute a queue estimate from data that does not
    exist and call the output a probability, this policy asks the caller for
    the assumption and records it.

    No Vietnamese document supplies a value either, and none could: the
    rulebook settles the *rule* -- priority is price first, time second, with
    no size priority and no pro-rata (rulebook 2.4, QD 352 Dieu 7, 16,
    confidence high) -- and what is missing is the *data* to apply it, namely
    our own position in a time queue that a corpus with no order ids, in which
    81% of best-quote changes carry no trade, cannot reconstruct.

    So the default of ``0.5`` is a **stated convention with no empirical
    content**, chosen as the midpoint of the bracket ``hard`` and ``soft``
    already draw, and it carries no claim that half of touches fill in the
    Vietnamese market. The intended use is a sweep -- see
    :func:`probabilistic_sweep` and :func:`compare_policies` -- reported as a
    range, not a single run at the default reported as a point estimate.

    ``p = 0`` is not ``hard`` and ``p = 1`` is not ``soft``
    ------------------------------------------------------------------
    Worth stating because it looks like it should be. At ``p_touch = 0`` this
    policy answers ``NO_FILL`` at the touch, whereas ``hard`` answers
    ``INDETERMINATE``: one asserts the order did not fill, the other asserts
    that the data cannot say. Those are different claims and they land in
    different places -- only ``hard``'s reaches ``IndeterminateReport``. The
    endpoints of the probabilistic arm bracket the *fill* counts, never the
    ignorance counts.

    ``p_touch`` is per **evaluated interval**
    ------------------------------------------------------------------
    A resting order that draws a no is not killed; it stays ``RESTING`` and is
    re-drawn on the next interval it touches at (design section 12 --
    ``INDETERMINATE`` and a no-fill are events, never states). Over ``n``
    touching intervals the order survives unfilled with probability
    ``(1 - p) ** n``, so ``p`` is emphatically not a per-order fill rate, and a
    run at daily resolution and the same run at tick resolution are not the
    same experiment at the same ``p``.

    Where it still returns ``INDETERMINATE``
    ------------------------------------------------------------------
    A draw is only permitted where the data has already established that the
    order was **eligible** -- that the market traded at its price at all. Being
    probabilistic is not a licence to decide everything, and the distinction
    the ignorance rate depends on is between *"eligible, and the draw said no"*
    (a ``NO_FILL``) and *"the data cannot say whether it was even eligible"*
    (an ``INDETERMINATE``). This policy keeps seven of the latter:

    1. the session phase is unknown, so no mechanic applies (base class);
    2. the interval carries no traded price at all;
    3. a single point price short of the limit, with no extreme -- a trade
       through the limit cannot be ruled out, so eligibility is unestablished
       and there is nothing to draw *for*;
    4. a market-family order, whose depth walk is not observable;
    5. an established fill whose size cannot be bounded, when a cap is in
       force and ``interval.volume`` is absent;
    6. an established fill whose round lot cannot be resolved at the instant,
       likewise only when a cap is in force -- see
       :meth:`BaseFillPolicy._lot`;
    7. the auction marginal price, unless the caller explicitly opts in --
       see ``p_auction_margin``.
    """

    kind: ClassVar[str] = 'probabilistic'

    def __init__(
        self,
        seed: int,
        *,
        max_participation: Optional[Decimal],
        p_touch: Decimal = Decimal('0.5'),
        p_auction_margin: Optional[Decimal] = None,
    ) -> None:
        """
        Args:
            seed: required, and required to be an ``int``. There is no default
                and there is no unseeded mode: a probabilistic result that
                cannot be reproduced is not a result, and a default seed would
                let a run be reproducible by accident rather than by record.
                It is carried in :attr:`signature`, so every decision this
                policy makes names the seed that made it.
            max_participation: **keyword-only and required**, because the
                choice materially changes which decisions are answerable and
                must therefore be made by the caller rather than by this class.
                A ``Decimal`` in ``(0, 1]`` applies ``hard``'s participation
                cap, which turns a would-be fill into an ``INDETERMINATE``
                naming ``DataField.VOLUME`` wherever the source does not serve
                volume -- ``TickSource``, and the ticker-days ``DataHubSource``
                has no ``quote_dailyvolume`` row for. ``None`` takes the
                uncapped size assumption instead (the caller's whole size was
                available), which isolates the touch as the only axis on which
                this arm differs from ``hard``. Whichever is chosen is recorded
                in :attr:`signature`.
            p_touch: the probability that an order at a price the market
                touched but did not trade through would have filled. A declared
                assumption, not a measurement -- see the class docstring.
                ``[0, 1]`` inclusive, both endpoints meaningful.
            p_auction_margin: the probability of being allocated at an
                auction's exact clearing price. ``None``, the default, means
                **do not model it**, and the policy returns ``INDETERMINATE``
                there exactly as ``hard`` does. That default is not timidity:
                the continuous touch is a case where the rule is known and the
                data is missing, whereas allocation at the marginal price is
                recorded as **UNVERIFIED for the ATO/ATC cross** in rulebook
                2.4 -- *no Vietnamese document states the rule at all*. Drawing
                a number for a rule nobody has written down is a different and
                worse act than drawing one for a queue position nobody can
                observe, so it is opt-in and the opt-in is stamped on every
                decision the run produced. (The one adjacent fact the rulebook
                does carry: the HNX *post-close* periodic auction allocates
                "tren co so phan bo theo khoi luong lenh nhap vao he thong",
                i.e. pro-rata by entered volume, confidence **low** and for
                that phase only -- and no order this package can represent
                trades in that phase, since ``OrderType`` has no PLO member.)

        Raises:
            TypeError: on a non-``int`` seed, a ``bool`` seed, or a ``float``
                probability. Rates are ``Decimal`` here; ``True`` silently
                meaning seed 1 is a bug worth refusing.
            ValueError: on a probability outside ``[0, 1]``, or a
                ``max_participation`` outside ``(0, 1]``.
        """
        if isinstance(seed, bool) or not isinstance(seed, int):
            raise TypeError(
                f'seed must be an int, got {type(seed).__name__}; a '
                f'probabilistic run that cannot be reproduced is not a result'
            )
        self.seed = seed
        self.p_touch = _validated_probability(p_touch, 'p_touch')
        self.p_auction_margin = (
            None if p_auction_margin is None
            else _validated_probability(p_auction_margin, 'p_auction_margin'))
        self.max_participation: Optional[Decimal] = (
            self._validated_participation(max_participation,
                                          allow_uncapped=True))

    # -- what the run records -------------------------------------------

    @property
    def signature(self) -> str:
        """Every parameter that could change a decision, including the seed.

        ``probabilistic(seed=20220329,p_touch=0.5,max_participation=uncapped,
        p_auction_margin=off)``. Long on purpose: this string is what
        ``SessionProvenance.fill_policy_kind`` carries and what is stamped on
        every ``FillDecision``, so anything omitted from it is a parameter a
        reader cannot recover from the result. No spaces, because
        :func:`stamp_policy` forbids the ``': '`` separator in a signature and
        a comma-space is a needless near-miss.
        """
        cap = ('uncapped' if self.max_participation is None
               else str(self.max_participation))
        margin = ('off' if self.p_auction_margin is None
                  else str(self.p_auction_margin))
        return (f'{self.kind}(seed={self.seed},p_touch={self.p_touch},'
                f'max_participation={cap},p_auction_margin={margin})')

    @property
    def assumptions(self) -> Tuple[str, ...]:
        cap = (
            'Size: uncapped -- this run assumes the caller\'s own size was '
            'available at the touch, which is the soft arm\'s assumption and '
            'is not a market observation.'
            if self.max_participation is None else
            f'Participation cap: at most {self.max_participation} of the '
            f'volume observed in the evaluated interval, aggregated across all '
            f'of the caller\'s live orders in the instrument. A modelling '
            f'convention, not a sourced rule.'
        )
        margin = (
            'Auction marginal price: NOT modelled. Allocation at the clearing '
            'price is UNVERIFIED for the ATO/ATC cross (rulebook 2.4) and this '
            'run returns INDETERMINATE there.'
            if self.p_auction_margin is None else
            f'Auction marginal price: modelled at p={self.p_auction_margin}. '
            f'Allocation at the clearing price is UNVERIFIED for the ATO/ATC '
            f'cross (rulebook 2.4) -- no Vietnamese document states the rule, '
            f'so this figure is an assumption about an unwritten rule and any '
            f'result depending on it must say so.'
        )
        return super().assumptions + (
            f'Probabilistic fills: an order at a price the market touched but '
            f'did not trade through fills with probability p_touch='
            f'{self.p_touch} per evaluated interval. That value is supplied by '
            f'the caller and is not derived from data or from any rule: no '
            f'Vietnamese document states a fill probability, and the queue '
            f'position it would stand in for cannot be reconstructed from a '
            f'corpus with no order ids in which 81% of best-quote changes '
            f'carry no trade. Report it as a range over p, not as a point '
            f'estimate.',
            f'Reproducibility: every draw is a pure function of seed='
            f'{self.seed} and the question asked (order id, instrument, '
            f'interval, phase, side, price), so the run reproduces exactly and '
            f'is independent of the order in which orders were evaluated.',
            cap,
            margin,
        )

    # -- the draw -------------------------------------------------------

    def draw(self, order: OrderRecord, interval: MarketInterval,
             price: Decimal) -> Decimal:
        """This policy's uniform draw for one question, in ``[0, 1)``.

        Public because a fill that cannot be re-checked has not really been
        recorded: given a stamped decision, a reader can read the seed out of
        the signature, rebuild the key with :func:`draw_key` and land on this
        number. It is also what makes two useful properties testable rather
        than merely claimed:

        * **order-independence** -- the answer does not depend on what else was
          in the run, or on the sequence in which the session evaluated it;
        * **nesting under a sweep** -- because the draw ignores ``p_touch``,
          two policies sharing a seed are ordered: an order that fills at
          ``p = 0.3`` also fills at ``p = 0.5``. A sweep is then a monotone
          family and its endpoints are a genuine bracket, rather than a set of
          unrelated random runs whose spread is partly the RNG's.
        """
        return fill_draw(self.seed, draw_key(order, interval, price))

    def _drawn(
        self,
        order: OrderRecord,
        interval: MarketInterval,
        price: Decimal,
        probability: Decimal,
        subject: str,
    ) -> Tuple[bool, str]:
        """Draw, and render the sentence that records it on the decision."""
        value = self.draw(order, interval, price)
        hit = value < probability
        return hit, (
            f'{"filled" if hit else "did not fill"} on a seeded draw of '
            f'{value} against {subject} of {probability} '
            f'[key {draw_key(order, interval, price)}]'
        )

    # -- continuous -----------------------------------------------------

    def _continuous(self, order, interval, rules, *, already_filled,
                    instrument) -> FillDecision:
        limit = order.order.limit_price
        if limit is None:
            # Identical to hard's refusal, and for the same reason: how far a
            # market-family order walks the book is a function of depth, and
            # BookLevel.size is None on every corpus here. A probability drawn
            # here would be standing in for the depth rather than for the queue
            # -- a market-impact assumption, which section 3 forbids outright.
            return self._market_family_undecidable(interval)

        evidence = self._price_test(order, interval)
        if evidence.verdict is _PriceVerdict.SHORT:
            return _no_extreme_reached(evidence, limit)
        if evidence.verdict is _PriceVerdict.THROUGH:
            # Proven. A draw here would throw away evidence the data actually
            # carries, which would make this arm worse than hard rather than
            # merely more optimistic -- and confidence stays 1, because nothing
            # about this fill was modelled.
            return self._sized_fill(order, interval, rules, limit,
                                    FillEvidence.TRADED_THROUGH,
                                    already_filled=already_filled,
                                    instrument=instrument)
        if evidence.verdict is _PriceVerdict.UNPROVEN:
            return _unproven(evidence, limit)
        if evidence.verdict is _PriceVerdict.BLANK:
            return _blank(evidence)

        # AT: the market traded at our exact price. Eligibility is established
        # by the data; only our place in the time queue is not. This is the one
        # question this policy answers differently from hard, and the only
        # place it draws.
        hit, told = self._drawn(order, interval, limit, self.p_touch,
                                'p_touch')
        if not hit:
            return FillDecision.no_fill(
                f'the market touched the limit at {evidence.observed} but did '
                f'not trade through it, and this order {told}'
            )
        return self._sized_fill(order, interval, rules, limit,
                                FillEvidence.MODELLED,
                                already_filled=already_filled,
                                instrument=instrument,
                                confidence=self.p_touch)

    def _market_family_undecidable(self, interval) -> FillDecision:
        """Shared verbatim with ``hard``; see :meth:`HardFillPolicy`."""
        missing = (DataField.BOOK_SIZE if interval.book is not None
                   else DataField.BOOK)
        return FillDecision.indeterminate(
            'a market-family order walks the book, and the depth it would '
            'walk is not observable here; assuming it fills at the touch '
            'would be a market-impact assumption',
            [missing],
        )

    # -- auction --------------------------------------------------------

    def _auction(self, order, interval, rules, *, already_filled,
                 instrument) -> FillDecision:
        clearing, field = _clearing_price(order, interval)
        if clearing is None:
            return FillDecision.indeterminate(
                'no published cross price for this auction, so whether it '
                'crossed at all cannot be established',
                [field] if field is not None else (),
            )

        limit = order.order.limit_price
        if limit is None:
            tif = TIME_IN_FORCE[order.order.order_type]
            if tif is not TimeInForce.AUCTION_ONLY:
                return FillDecision.indeterminate(
                    'a market-family order carries into an auction as its '
                    'residual limit one tick beyond the last match, and that '
                    'conversion is not modelled here',
                    [DataField.BOOK_SIZE],
                )
            # ATO/ATC that reached its own cross is through-priced under HOSE
            # step (a) and fills in full by rule -- no draw, and confidence 1.
            return self._sized_fill(order, interval, rules, clearing,
                                    FillEvidence.AUCTION_PRICE,
                                    already_filled=already_filled,
                                    instrument=instrument)

        reach = _reach(order.order.side, clearing, limit)
        if reach < 0:
            return FillDecision.no_fill(
                f'the auction cleared at {clearing}, past a limit of {limit}; '
                f'a call auction cannot execute an order priced away from the '
                f'clearing price'
            )
        if reach > 0:
            return self._sized_fill(order, interval, rules, clearing,
                                    FillEvidence.AUCTION_PRICE,
                                    already_filled=already_filled,
                                    instrument=instrument)

        if self.p_auction_margin is None:
            return FillDecision.indeterminate(
                f'the auction cleared exactly at the limit of {limit}; '
                f'allocation at the marginal price is UNVERIFIED for the '
                f'ATO/ATC cross -- no Vietnamese document states the rule '
                f'(rulebook 2.4), so this policy will not draw for it unless '
                f'the caller sets p_auction_margin and accepts that the run '
                f'models an unwritten rule',
                (),
            )
        hit, told = self._drawn(order, interval, clearing,
                                self.p_auction_margin, 'p_auction_margin')
        if not hit:
            return FillDecision.no_fill(
                f'the auction cleared exactly at the limit of {limit} and this '
                f'order {told}'
            )
        return self._sized_fill(order, interval, rules, clearing,
                                FillEvidence.MODELLED,
                                already_filled=already_filled,
                                instrument=instrument,
                                confidence=self.p_auction_margin)


def probabilistic_sweep(
    seed: int,
    probabilities: Sequence[Decimal],
    *,
    max_participation: Optional[Decimal],
    p_auction_margin: Optional[Decimal] = None,
) -> Tuple[ProbabilisticFillPolicy, ...]:
    """One policy per ``p_touch``, all sharing a seed. The intended use.

    ``p_touch`` has no sourced value, so a single run at one ``p`` is a point
    estimate of something nobody has measured. A sweep reported as a range is
    the honest form, and sharing the seed across the family is what makes the
    range interpretable: the draws are identical, so the only thing that varies
    between two members is the threshold, and the family is nested -- an order
    that fills at a lower ``p`` fills at every higher one.

    Feed the result straight to :func:`compare_policies`.

    Raises:
        ValueError: on an empty or duplicated list of probabilities. A
            duplicate would produce two policies with the same signature, which
            :func:`compare_policies` refuses because it could not then
            attribute a column.
    """
    if not probabilities:
        raise ValueError('a sweep needs at least one probability')
    if len(set(probabilities)) != len(probabilities):
        raise ValueError(
            f'a sweep must not repeat a probability, got {list(probabilities)}')
    return tuple(
        ProbabilisticFillPolicy(seed, p_touch=p,
                                max_participation=max_participation,
                                p_auction_margin=p_auction_margin)
        for p in probabilities
    )


